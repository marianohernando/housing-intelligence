"""Write hi_domain.geo.zoning_data from data/catalog/zoning/search_scope.yaml (D-238).

The YAML is the versioned source, with the publication it copies; the API image only carries
the Python packages, so the search reads this generated module.
Usage: uv run python scripts/export_search_scope.py [--check]
"""

import sys
from pathlib import Path
from typing import Any

import yaml

from hi_contracts.public import SearchScope
from hi_domain.geo.codes import ine_municipality_from_cm

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "catalog" / "zoning" / "search_scope.yaml"
TARGET = ROOT / "packages" / "domain" / "src" / "hi_domain" / "geo" / "zoning_data.py"
PARTS = {s.value for s in SearchScope} - {SearchScope.ALL.value}


def scope_by_zone(spec: dict[str, Any]) -> dict[str, str]:
    """Each statistical zone in exactly one part of the region."""
    if set(spec["scopes"]) != PARTS:
        msg = f"scopes must be exactly {sorted(PARTS)}"
        raise ValueError(msg)
    by_zone = {zone: scope for scope, zones in spec["scopes"].items() for zone in zones}
    codes = [zone["code"] for zone in spec["zones"]]
    if sorted(by_zone) != sorted(codes) or len(codes) != len(set(codes)):
        msg = "every zone must be in one scope, once"
        raise ValueError(msg)
    return by_zone


def scope_by_municipio(spec: dict[str, Any]) -> dict[str, str]:
    """INE code of each municipio -> its part of the region."""
    by_zone = scope_by_zone(spec)
    result: dict[str, str] = {}
    for zone in spec["zones"]:
        for municipio in zone["municipios"]:
            ine = ine_municipality_from_cm(municipio["cm_code"])
            if ine in result:
                msg = f"{ine} ({municipio['name']}) is in two zones"
                raise ValueError(msg)
            result[ine] = by_zone[zone["code"]]
    return result


def render(spec: dict[str, Any]) -> str:
    source = spec["source"]
    lines = [
        '"""Generated by scripts/export_search_scope.py from',
        "data/catalog/zoning/search_scope.yaml: do not edit by hand.",
        "",
        f"Source: {source['publisher']},",
        f"«{source['title']}»,",
        f"{source['section']}",
        f"(retrieved {source['retrieved_at']}).",
        '"""',
        "",
        "SCOPE_BY_MUNICIPIO: dict[str, str] = {",
        *(f'    "{ine}": "{scope}",' for ine, scope in sorted(scope_by_municipio(spec).items())),
        "}",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    content = render(yaml.safe_load(SOURCE.read_text(encoding="utf-8")))
    if "--check" not in sys.argv:
        TARGET.write_text(content, encoding="utf-8")
        print("wrote", TARGET.relative_to(ROOT))
        return 0
    if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
        print("stale", TARGET.name, "(run uv run python scripts/export_search_scope.py)")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
